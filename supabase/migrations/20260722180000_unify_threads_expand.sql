create or replace function public.ingest_crawl_items(
	p_crawl_source text,
	p_items jsonb
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
	v_result jsonb;
begin
	if p_crawl_source not in ('arcalive', 'battlepage', 'insagirl') then
		raise exception using errcode = '22023', message = 'Unsupported crawl source.';
	end if;
	if p_items is null or jsonb_typeof(p_items) <> 'array' then
		raise exception using errcode = '22023', message = 'Crawl items must be a JSON array.';
	end if;
	if jsonb_array_length(p_items) > 1000 then
		raise exception using errcode = '22023', message = 'A crawl batch cannot exceed 1000 items.';
	end if;

	with normalized_payload as materialized (
		select distinct on (btrim(item ->> 'url'))
			btrim(item ->> 'url') as url,
			nullif(item ->> 'title', '') as title,
			nullif(item ->> 'description', '') as description,
			nullif(item ->> 'host', '') as host,
			case
				when coalesce(nullif(item ->> 'type', ''), 'normal') in ('media', 'youtube')
					then 'normal'
				else coalesce(nullif(item ->> 'type', ''), 'normal')
			end as type,
			case
				when jsonb_typeof(item -> 'tag') = 'array' then
					array(select jsonb_array_elements_text(item -> 'tag'))
				else null
			end as tag
		from jsonb_array_elements(p_items) as payload(item)
		where nullif(btrim(item ->> 'url'), '') is not null
		order by btrim(item ->> 'url')
	),
	claimed as (
		insert into public."crawl-history" (url, crawl_source, host)
		select url, p_crawl_source, host
		from normalized_payload
		on conflict (crawl_source, url) do nothing
		returning url
	),
	inserted as (
		insert into public.threads (url, title, description, host, type, tag, state)
		select payload.url, payload.title, payload.description, payload.host,
			payload.type, payload.tag, 'inbox'
		from normalized_payload as payload
		inner join claimed using (url)
		returning url
	),
	counts as (
		select
			(select count(*) from normalized_payload) as input_count,
			(select count(*) from inserted) as inserted_count
	)
	select jsonb_build_object(
		'insertedCount', inserted_count,
		'skippedCount', input_count - inserted_count
	)
	into v_result
	from counts;

	return coalesce(v_result, jsonb_build_object('insertedCount', 0, 'skippedCount', 0));
end;
$$;

revoke all on function public.ingest_crawl_items(text, jsonb)
	from public, anon, authenticated;
grant execute on function public.ingest_crawl_items(text, jsonb) to service_role;

create function public.get_thread_storage_consistency()
returns table (
	state text,
	canonical_count bigint,
	legacy_count bigint,
	mismatch_count bigint
)
language sql
stable
security invoker
set search_path = ''
as $$
	with legacy as (
		select id, captured_at as created_at, type, url, title, description, host, tag,
			'inbox'::text as state, captured_at, created_at as state_changed_at
		from public."new-threads"
		union all
		select id, captured_at, type, url, title, description, host, tag,
			'saved', captured_at, created_at
		from public."quick-save"
		union all
		select id, captured_at, type, url, title, description, host, tag,
			'trash', captured_at, created_at
		from public.trash
	),
	states(state) as (
		values ('inbox'::text), ('saved'::text), ('trash'::text)
	)
	select
		states.state,
		(select count(*) from public.threads where threads.state = states.state),
		(select count(*) from legacy where legacy.state = states.state),
		(
			select count(*)
			from public.threads as thread
			full join legacy on legacy.id = thread.id
			where coalesce(thread.state, legacy.state) = states.state
				and (
					thread.id is null
					or legacy.id is null
					or row(
						thread.created_at, thread.type, thread.url, thread.title,
						thread.description, thread.host, thread.tag, thread.state,
						thread.captured_at, thread.state_changed_at
					) is distinct from row(
						legacy.created_at, legacy.type, legacy.url, legacy.title,
						legacy.description, legacy.host, legacy.tag, legacy.state,
						legacy.captured_at, legacy.state_changed_at
					)
				)
		)
	from states
	order by states.state;
$$;

