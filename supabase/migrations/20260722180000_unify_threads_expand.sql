begin;

set local lock_timeout = '5s';
set local statement_timeout = '60s';

lock table public."new-threads", public."quick-save", public.trash
	in share row exclusive mode;

do $$
begin
	if exists (
		select legacy.id
		from (
			select id from public."new-threads"
			union all
			select id from public."quick-save"
			union all
			select id from public.trash
		) as legacy
		group by legacy.id
		having count(*) > 1
	) then
		raise exception using
			errcode = '23505',
			message = 'Legacy thread IDs overlap across tables. The threads migration was not applied.';
	end if;
end;
$$;

create table public.threads (
	id bigint generated by default as identity primary key,
	created_at timestamp with time zone not null default now(),
	type text,
	url text,
	title text,
	description text,
	host text,
	tag text[],
	state text not null default 'inbox',
	captured_at timestamp with time zone not null default now(),
	state_changed_at timestamp with time zone not null default now(),
	constraint threads_state_check check (state in ('inbox', 'saved', 'trash')),
	constraint threads_no_removed_media_types check (type not in ('media', 'youtube'))
);

comment on table public.threads is
	'Applemint thread source of truth. Legacy thread tables are synchronized projections during rollout.';
comment on column public.threads.created_at is
	'Logical thread creation time. It never changes when the thread state changes.';
comment on column public.threads.captured_at is
	'Time when the thread was first captured from its source. It is immutable across state changes.';
comment on column public.threads.state_changed_at is
	'Time when the thread entered its current state.';

insert into public.threads (
	id,
	created_at,
	type,
	url,
	title,
	description,
	host,
	tag,
	state,
	captured_at,
	state_changed_at
)
select
	thread.id,
	thread.captured_at,
	thread.type,
	thread.url,
	thread.title,
	thread.description,
	thread.host,
	thread.tag,
	'inbox',
	thread.captured_at,
	thread.created_at
from public."new-threads" as thread
union all
select
	thread.id,
	thread.captured_at,
	thread.type,
	thread.url,
	thread.title,
	thread.description,
	thread.host,
	thread.tag,
	'saved',
	thread.captured_at,
	thread.created_at
from public."quick-save" as thread
union all
select
	thread.id,
	thread.captured_at,
	thread.type,
	thread.url,
	thread.title,
	thread.description,
	thread.host,
	thread.tag,
	'trash',
	thread.captured_at,
	thread.created_at
from public.trash as thread;

do $$
declare
	v_max_id bigint;
	v_legacy_count bigint;
	v_thread_count bigint;
	v_mismatch_count bigint;
begin
	select max(id) into v_max_id from public.threads;
	if v_max_id is null then
		perform setval(pg_get_serial_sequence('public.threads', 'id'), 1, false);
	else
		perform setval(pg_get_serial_sequence('public.threads', 'id'), v_max_id, true);
	end if;

	select
		(select count(*) from public."new-threads")
		+ (select count(*) from public."quick-save")
		+ (select count(*) from public.trash)
	into v_legacy_count;
	select count(*) into v_thread_count from public.threads;

	with legacy as (
		select id, captured_at as created_at, type, url, title, description, host, tag,
			'inbox'::text as state, captured_at, created_at as state_changed_at
		from public."new-threads"
		union all
		select id, captured_at, type, url, title, description, host, tag,
			'saved', captured_at, created_at
		from public."quick-save"
		union all
		select id, captured_at, type, url, title, description, host, tag,
			'trash', captured_at, created_at
		from public.trash
	)
	select count(*)
	into v_mismatch_count
	from legacy
	full join public.threads as thread using (id)
	where legacy.id is null
		or thread.id is null
		or row(
			legacy.created_at,
			legacy.type,
			legacy.url,
			legacy.title,
			legacy.description,
			legacy.host,
			legacy.tag,
			legacy.state,
			legacy.captured_at,
			legacy.state_changed_at
		) is distinct from row(
			thread.created_at,
			thread.type,
			thread.url,
			thread.title,
			thread.description,
			thread.host,
			thread.tag,
			thread.state,
			thread.captured_at,
			thread.state_changed_at
		);

	if v_legacy_count <> v_thread_count or v_mismatch_count <> 0 then
		raise exception using
			errcode = 'P0001',
			message = format(
				'Thread backfill verification failed: legacy=%s threads=%s mismatches=%s.',
				v_legacy_count,
				v_thread_count,
				v_mismatch_count
			);
	end if;
end;
$$;

