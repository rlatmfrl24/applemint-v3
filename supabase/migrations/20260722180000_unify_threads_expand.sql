create function private.sync_thread_legacy_projection()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
	v_thread public.threads;
begin
	if tg_op = 'DELETE' then
		delete from public."new-threads" where id = old.id;
		delete from public."quick-save" where id = old.id;
		delete from public.trash where id = old.id;
		return old;
	end if;

	v_thread := new;
	delete from public."new-threads" where id = v_thread.id;
	delete from public."quick-save" where id = v_thread.id;
	delete from public.trash where id = v_thread.id;

	if v_thread.state = 'inbox' then
		insert into public."new-threads" (
			id, created_at, type, url, title, description, host, tag, captured_at
		) values (
			v_thread.id, v_thread.state_changed_at, v_thread.type, v_thread.url,
			v_thread.title, v_thread.description, v_thread.host, v_thread.tag,
			v_thread.captured_at
		);
	elsif v_thread.state = 'saved' then
		insert into public."quick-save" (
			id, created_at, type, url, title, description, host, tag, captured_at
		) values (
			v_thread.id, v_thread.state_changed_at, v_thread.type, v_thread.url,
			v_thread.title, v_thread.description, v_thread.host, v_thread.tag,
			v_thread.captured_at
		);
	else
		insert into public.trash (
			id, created_at, type, url, title, description, host, tag, captured_at
		) values (
			v_thread.id, v_thread.state_changed_at, v_thread.type, v_thread.url,
			v_thread.title, v_thread.description, v_thread.host, v_thread.tag,
			v_thread.captured_at
		);
	end if;

	return new;
end;
$$;

revoke all on function private.sync_thread_legacy_projection()
	from public, anon, authenticated, service_role;

create trigger sync_thread_legacy_projection
after insert or update or delete on public.threads
for each row
