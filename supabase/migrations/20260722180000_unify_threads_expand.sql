create or replace function public.move_thread(
	p_thread_id bigint,
	p_source text,
	p_destination text
)
returns bigint
language plpgsql
security invoker
set search_path = ''
as $$
declare
	v_source_state text;
	v_destination_state text;
	v_thread public.threads;
begin
	v_source_state := case p_source
		when 'new-threads' then 'inbox'
		when 'quick-save' then 'saved'
		when 'trash' then 'trash'
		else null
	end;
	v_destination_state := case p_destination
		when 'new-threads' then 'inbox'
		when 'quick-save' then 'saved'
		when 'trash' then 'trash'
		else null
	end;

	if v_source_state is null or v_destination_state is null then
		raise exception using
			errcode = '22023',
			message = format('Unsupported thread transition: %s -> %s', p_source, p_destination);
	end if;

	v_thread := public.transition_thread_state(
		p_thread_id,
		v_source_state,
		v_destination_state
	);
	return v_thread.id;
end;
$$;

