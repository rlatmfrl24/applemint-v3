begin;

set local lock_timeout = '5s';
set local statement_timeout = '60s';

create table public.web_push_subscriptions (
	id bigint generated by default as identity primary key,
	user_id uuid not null references auth.users (id) on delete cascade,
	endpoint text not null unique,
	p256dh text not null,
	auth text not null,
	expiration_time timestamp with time zone,
	active boolean not null default true,
	last_seen_at timestamp with time zone not null default now(),
	disabled_at timestamp with time zone,
	created_at timestamp with time zone not null default now(),
	updated_at timestamp with time zone not null default now(),
	constraint web_push_subscriptions_endpoint_check check (
		octet_length(endpoint) between 16 and 4096
		and endpoint ~ '^https://'
	),
	constraint web_push_subscriptions_p256dh_check check (
		octet_length(p256dh) between 32 and 512
		and p256dh ~ '^[A-Za-z0-9_-]+$'
	),
	constraint web_push_subscriptions_auth_check check (
		octet_length(auth) between 8 and 128
		and auth ~ '^[A-Za-z0-9_-]+$'
	),
	constraint web_push_subscriptions_disabled_check check (
		(active and disabled_at is null)
		or (not active and disabled_at is not null)
	)
);

create index web_push_subscriptions_active_idx
	on public.web_push_subscriptions (id)
	where active;
create index web_push_subscriptions_inactive_cleanup_idx
	on public.web_push_subscriptions (updated_at)
	where not active;

create table public.web_push_deliveries (
	id bigint generated by default as identity primary key,
	run_id bigint not null references public.crawl_runs (id) on delete cascade,
	subscription_id bigint not null
		references public.web_push_subscriptions (id) on delete cascade,
	source text not null,
	inserted_count integer not null,
	state text not null default 'pending',
	available_at timestamp with time zone not null default now(),
	lease_token uuid,
	lease_expires_at timestamp with time zone,
	attempt_count integer not null default 0,
	delivered_at timestamp with time zone,
	last_error_code text,
	created_at timestamp with time zone not null default now(),
	updated_at timestamp with time zone not null default now(),
	constraint web_push_deliveries_run_subscription_key
		unique (run_id, subscription_id),
	constraint web_push_deliveries_source_check
		check (source in ('arcalive', 'battlepage', 'insagirl')),
	constraint web_push_deliveries_count_check check (inserted_count > 0),
	constraint web_push_deliveries_state_check check (
		state in ('pending', 'processing', 'retry', 'delivered', 'dead', 'skipped')
	),
	constraint web_push_deliveries_attempt_check check (
		attempt_count between 0 and 6
	),
	constraint web_push_deliveries_lease_check check (
		(
			state = 'processing'
			and lease_token is not null
			and lease_expires_at is not null
		)
		or (
			state <> 'processing'
			and lease_token is null
			and lease_expires_at is null
		)
	),
	constraint web_push_deliveries_delivered_check check (
		(state = 'delivered' and delivered_at is not null)
		or (state <> 'delivered' and delivered_at is null)
	),
	constraint web_push_deliveries_error_code_check check (
		last_error_code is null
		or (
			octet_length(last_error_code) between 1 and 80
			and last_error_code ~ '^[a-z0-9-]+$'
		)
	)
);

create index web_push_deliveries_claim_idx
	on public.web_push_deliveries (available_at, id)
	where state in ('pending', 'retry');
create index web_push_deliveries_expired_lease_idx
	on public.web_push_deliveries (lease_expires_at, id)
	where state = 'processing';
create index web_push_deliveries_badge_idx
	on public.web_push_deliveries (subscription_id, created_at)
	where state <> 'skipped';
create index web_push_deliveries_cleanup_idx
	on public.web_push_deliveries (updated_at)
	where state in ('delivered', 'skipped', 'dead');

alter table public.web_push_subscriptions enable row level security;
alter table public.web_push_deliveries enable row level security;

revoke all on table public.web_push_subscriptions
	from public, anon, authenticated;
revoke all on table public.web_push_deliveries
	from public, anon, authenticated;
revoke all on sequence public.web_push_subscriptions_id_seq
	from public, anon, authenticated;
revoke all on sequence public.web_push_deliveries_id_seq
	from public, anon, authenticated;

grant all on table public.web_push_subscriptions to service_role;
grant all on table public.web_push_deliveries to service_role;
grant all on sequence public.web_push_subscriptions_id_seq to service_role;
grant all on sequence public.web_push_deliveries_id_seq to service_role;

create or replace function public.upsert_web_push_subscription(
	p_endpoint text,
	p_p256dh text,
	p_auth text,
	p_expiration_time timestamp with time zone default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
	v_user_id uuid := auth.uid();
	v_now timestamp with time zone := now();
	v_subscription_id bigint;
begin
	if not public.is_applemint_owner() or v_user_id is null then
		raise exception using
			errcode = '42501',
			message = 'Only the Applemint owner can manage web push subscriptions.';
	end if;
	if p_endpoint is null
		or octet_length(p_endpoint) not between 16 and 4096
		or p_endpoint !~ '^https://'
		or p_p256dh is null
		or octet_length(p_p256dh) not between 32 and 512
		or p_p256dh !~ '^[A-Za-z0-9_-]+$'
		or p_auth is null
		or octet_length(p_auth) not between 8 and 128
		or p_auth !~ '^[A-Za-z0-9_-]+$'
	then
		raise exception using
			errcode = '22023',
			message = 'Invalid web push subscription.';
	end if;

	insert into public.web_push_subscriptions (
		user_id,
		endpoint,
		p256dh,
		auth,
		expiration_time,
		active,
		last_seen_at,
		disabled_at,
		updated_at
	)
	values (
		v_user_id,
		p_endpoint,
		p_p256dh,
		p_auth,
		p_expiration_time,
		true,
		v_now,
		null,
		v_now
	)
	on conflict (endpoint) do update
	set
		user_id = excluded.user_id,
		p256dh = excluded.p256dh,
		auth = excluded.auth,
		expiration_time = excluded.expiration_time,
		active = true,
		last_seen_at = v_now,
		disabled_at = null,
		updated_at = v_now
	returning id into v_subscription_id;

	update public.web_push_deliveries
	set
		state = 'skipped',
		lease_token = null,
		lease_expires_at = null,
		last_error_code = 'subscription-reactivated',
		updated_at = v_now
	where subscription_id = v_subscription_id
		and state in ('pending', 'retry', 'processing')
		and created_at <= v_now;

	return jsonb_build_object('active', true);
end;
$$;

