create or replace function public.retry_web_push_delivery(
	p_delivery_id bigint,
	p_lease_token uuid,
	p_error_code text
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
	v_now timestamp with time zone := now();
	v_attempt_count integer;
	v_created_at timestamp with time zone;
	v_state text;
	v_delay interval;
begin
	if p_error_code is null
		or octet_length(p_error_code) not between 1 and 80
		or p_error_code !~ '^[a-z0-9-]+$'
	then
		raise exception using
			errcode = '22023',
			message = 'Invalid web push error code.';
	end if;

	select delivery.attempt_count, delivery.created_at
	into v_attempt_count, v_created_at
	from public.web_push_deliveries as delivery
	where delivery.id = p_delivery_id
		and delivery.lease_token = p_lease_token
		and delivery.state = 'processing'
	for update;

	if v_attempt_count is null then
		return jsonb_build_object('updated', false);
	end if;

	if v_attempt_count >= 6 or v_created_at <= v_now - interval '24 hours' then
		v_state := 'dead';
		v_delay := interval '0 seconds';
	else
		v_state := 'retry';
		v_delay := (array[
			interval '1 minute',
			interval '5 minutes',
			interval '30 minutes',
			interval '2 hours',
			interval '6 hours'
		])[v_attempt_count];
	end if;

	update public.web_push_deliveries
	set
		state = v_state,
		available_at = case
			when v_state = 'retry' then v_now + v_delay
			else available_at
		end,
		lease_token = null,
		lease_expires_at = null,
		last_error_code = p_error_code,
		updated_at = v_now
	where id = p_delivery_id
		and lease_token = p_lease_token
		and state = 'processing';

	return jsonb_build_object(
		'updated',
		true,
		'state',
		v_state,
		'availableAt',
		case when v_state = 'retry' then v_now + v_delay else null end
	);
end;
$$;

create or replace function public.invalidate_web_push_subscription(
	p_delivery_id bigint,
	p_lease_token uuid,
	p_error_code text
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
	v_now timestamp with time zone := now();
	v_subscription_id bigint;
	v_skipped_count integer := 0;
begin
	if p_error_code not in ('push-404', 'push-410') then
		raise exception using
			errcode = '22023',
			message = 'Unsupported web push invalidation code.';
	end if;

	update public.web_push_deliveries
	set
		state = 'dead',
		lease_token = null,
		lease_expires_at = null,
		last_error_code = p_error_code,
		updated_at = v_now
	where id = p_delivery_id
		and lease_token = p_lease_token
		and state = 'processing'
	returning subscription_id into v_subscription_id;

	if v_subscription_id is null then
		return jsonb_build_object('invalidated', false, 'skippedCount', 0);
	end if;

	update public.web_push_subscriptions
	set
		active = false,
		disabled_at = v_now,
		updated_at = v_now
	where id = v_subscription_id;

	update public.web_push_deliveries
	set
		state = 'skipped',
		lease_token = null,
		lease_expires_at = null,
		last_error_code = 'subscription-invalid',
		updated_at = v_now
	where subscription_id = v_subscription_id
		and id <> p_delivery_id
		and state in ('pending', 'retry', 'processing');
	get diagnostics v_skipped_count = row_count;

	return jsonb_build_object(
		'invalidated',
		true,
		'skippedCount',
		v_skipped_count
	);
end;
$$;

create or replace function public.cleanup_web_push_notifications()
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
	v_delivery_count integer;
	v_subscription_count integer;
begin
	delete from public.web_push_deliveries
	where state in ('delivered', 'skipped', 'dead')
		and updated_at < now() - interval '90 days';
	get diagnostics v_delivery_count = row_count;

	delete from public.web_push_subscriptions
	where not active
		and updated_at < now() - interval '90 days';
	get diagnostics v_subscription_count = row_count;

	return jsonb_build_object(
		'deliveryCount',
		v_delivery_count,
		'subscriptionCount',
		v_subscription_count
	);
end;
$$;

create or replace function public.dispatch_due_web_push_notifications()
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
	v_base_url text;
	v_internal_secret text;
	v_request_id bigint;
begin
	perform pg_catalog.pg_advisory_xact_lock(
		pg_catalog.hashtextextended('applemint:web-push-dispatch', 0)
	);

	if not exists (
		select 1
		from public.web_push_deliveries as delivery
		inner join public.web_push_subscriptions as subscription
			on subscription.id = delivery.subscription_id
		where subscription.active
			and (
				(
					delivery.state in ('pending', 'retry')
					and delivery.available_at <= now()
				)
				or (
					delivery.state = 'processing'
					and delivery.lease_expires_at <= now()
				)
			)
	) then
		return jsonb_build_object('status', 'idle');
	end if;

	select secret.decrypted_secret
	into v_base_url
	from vault.decrypted_secrets as secret
	where secret.name = 'crawl_app_base_url'
	order by secret.created_at desc
	limit 1;

	select secret.decrypted_secret
	into v_internal_secret
	from vault.decrypted_secrets as secret
	where secret.name = 'crawl_internal_secret'
	order by secret.created_at desc
	limit 1;

	v_base_url := rtrim(v_base_url, '/');
	if v_base_url is null
		or v_base_url !~ '^https?://[^[:space:]]+$'
		or v_internal_secret is null
		or octet_length(v_internal_secret) < 32
	then
		return jsonb_build_object('status', 'configuration-missing');
	end if;

	select net.http_post(
		url := v_base_url || '/api/push/dispatch',
		headers := jsonb_build_object(
			'Content-Type', 'application/json',
			'x-applemint-internal-secret', v_internal_secret
		),
		body := jsonb_build_object('limit', 20),
		timeout_milliseconds := 60000
	)
	into v_request_id;

	return jsonb_build_object('status', 'dispatched', 'requestId', v_request_id);
end;
$$;

create or replace function public.finish_crawl_run(
	p_run_id bigint,
	p_lock_token uuid,
	p_result jsonb
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
	v_status text;
	v_warnings jsonb;
	v_failures jsonb;
	v_parser_observations jsonb;
	v_finished_at timestamp with time zone := now();
	v_duration_ms bigint;
	v_source text;
	v_run_trigger text;
	v_inserted_count integer;
begin
	if p_result is null or jsonb_typeof(p_result) <> 'object' then
		raise exception using errcode = '22023', message = 'Crawl run result must be a JSON object.';
	end if;
	v_status := p_result ->> 'status';
	if v_status not in ('succeeded', 'partial', 'failed') then
		raise exception using errcode = '22023', message = 'Unsupported terminal crawl run status.';
	end if;

	v_warnings := coalesce(p_result -> 'warnings', '[]'::jsonb);
	v_failures := coalesce(p_result -> 'failures', '[]'::jsonb);
	v_parser_observations := coalesce(p_result -> 'parserObservations', '[]'::jsonb);
	if jsonb_typeof(v_warnings) <> 'array'
		or jsonb_typeof(v_failures) <> 'array'
		or jsonb_typeof(v_parser_observations) <> 'array'
	then
		raise exception using errcode = '22023', message = 'Crawl run details must be JSON arrays.';
	end if;

	update public.crawl_runs
	set
		status = v_status,
		finished_at = v_finished_at,
		duration_ms = greatest(
			0,
			floor(extract(epoch from (v_finished_at - started_at)) * 1000)::bigint
		),
		retry_count = coalesce((p_result ->> 'retryCount')::integer, 0),
		recovered_count = coalesce((p_result ->> 'recoveredCount')::integer, 0),
		attempted_count = coalesce((p_result ->> 'attemptedCount')::integer, 0),
		succeeded_count = coalesce((p_result ->> 'succeededCount')::integer, 0),
		extracted_count = coalesce((p_result ->> 'extractedCount')::integer, 0),
		inserted_count = coalesce((p_result ->> 'insertedCount')::integer, 0),
		skipped_count = coalesce((p_result ->> 'skippedCount')::integer, 0),
		warning_count = coalesce((p_result ->> 'warningCount')::integer, 0),
		failure_count = coalesce((p_result ->> 'failureCount')::integer, 0),
		network_failure_count = coalesce((p_result ->> 'networkFailureCount')::integer, 0),
		parser_failure_count = coalesce((p_result ->> 'parserFailureCount')::integer, 0),
		timeout_failure_count = coalesce((p_result ->> 'timeoutFailureCount')::integer, 0),
		parser_valid_count = coalesce((p_result ->> 'parserValidCount')::integer, 0),
		parser_minimum_count = coalesce((p_result ->> 'parserMinimumCount')::integer, 0),
		warnings = v_warnings,
		failures = v_failures,
		parser_observations = v_parser_observations,
		error_stage = nullif(p_result ->> 'errorStage', ''),
		error_message = nullif(p_result ->> 'errorMessage', '')
	where id = p_run_id
		and lock_token = p_lock_token
		and status = 'running'
	returning duration_ms, source, run_trigger, inserted_count
	into v_duration_ms, v_source, v_run_trigger, v_inserted_count;

	if v_duration_ms is null then
		raise exception using errcode = 'P0002', message = 'Running crawl run was not found.';
	end if;

	if v_run_trigger = 'scheduled'
		and v_status in ('succeeded', 'partial')
		and v_inserted_count > 0
	then
		insert into public.web_push_deliveries (
			run_id,
			subscription_id,
			source,
			inserted_count
		)
		select
			p_run_id,
			subscription.id,
			v_source,
			v_inserted_count
		from public.web_push_subscriptions as subscription
		where subscription.active
			and (
				subscription.expiration_time is null
				or subscription.expiration_time > v_finished_at
			)
		on conflict (run_id, subscription_id) do nothing;
	end if;

	delete from public.crawl_run_locks
	where lock_token = p_lock_token
		and lock_key in ('global-crawl', 'crawl:' || v_source);

	return jsonb_build_object(
		'runId', p_run_id::text,
		'status', v_status,
		'durationMs', v_duration_ms
	);
end;
$$;

