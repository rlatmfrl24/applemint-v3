begin;
select plan(16);
-- Keep an existing local import intact while exercising the single-job contract transactionally.
update public.bookmark_jobs set state='paused' where kind='import';
select has_table('public', 'bookmarks', 'bookmarks have their own canonical store');
select ok((select relrowsecurity from pg_class where oid='public.bookmarks'::regclass), 'RLS enabled');
set local role authenticated;
select set_config('request.jwt.claim.sub', '480f5282-7933-4800-a970-d6bc8f05e8cb', true);
select lives_ok($$select public.bookmark_command('save','{"url":"https://example.com/a","title":"A","tags":["saved"],"note":"retain me"}')$$, 'owner saves');
select lives_ok($$select public.bookmark_command('save','{"url":"https://example.com/a"}')$$, 'duplicate save returns existing');
reset role;
select is((select count(*) from public.bookmarks where url='https://example.com/a'), 1::bigint, 'duplicate direct save is idempotent');
set local role authenticated;
select set_config('request.jwt.claim.sub', '11111111-1111-4111-8111-111111111111', true);
select is((select count(*) from public.bookmarks), 0::bigint, 'other user cannot read');
select throws_ok($$select public.bookmark_command('save','{"url":"https://example.com/forbidden"}')$$, '42501', 'owner required', 'other user cannot write');
select set_config('request.jwt.claim.sub', '480f5282-7933-4800-a970-d6bc8f05e8cb', true);
select lives_ok($$select public.bookmark_command('trash', jsonb_build_object('id',(select id from public.bookmarks where url='https://example.com/a'),'version',1))$$, 'trash is approved mutation');
select throws_ok($$select public.bookmark_command('restore', jsonb_build_object('id',(select id from public.bookmarks where url='https://example.com/a'),'version',1))$$, '40001', 'bookmark changed', 'stale mutation refused');
select lives_ok($$select public.bookmark_command('restore', jsonb_build_object('id',(select id from public.bookmarks where url='https://example.com/a'),'version',2))$$, 'restore succeeds');
reset role;
select is((select note from public.bookmarks where url='https://example.com/a'), 'retain me', 'restore preserves metadata');
select is((select state from public.bookmarks where url='https://example.com/a'), 'library', 'restore returns library');
select ok(not has_function_privilege('authenticated','public.bookmark_worker_claim()','execute'), 'worker is not callable by owner session');
select ok(not has_table_privilege('authenticated','public.bookmarks','update'), 'no bypass of atomic RPC');
set local role authenticated;
select set_config('request.jwt.claim.sub', '480f5282-7933-4800-a970-d6bc8f05e8cb', true);
select lives_ok($$select public.bookmark_command('start', '{"kind":"import","scope":"all","confirmed":true}')$$, 'import explicitly started');
select lives_ok($$select public.bookmark_command('start', '{"kind":"import","scope":"all","confirmed":true}')$$, 'same import job resumed instead of duplicate');
select * from finish();
rollback;
